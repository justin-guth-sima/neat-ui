/**
 * Example files in the order the page shows them: a numeric prefix (`2-`, `10-`) orders as a
 * number, so `2-` comes before `10-` with no zero padding; a file without one comes after those
 * that have one, in code-point order.
 */
const byExampleName = (a, b) => {
  const prefix = (name) => name.match(/^(\d+)-/)?.[1];
  const [first, second] = [prefix(a), prefix(b)];
  if (first && second) return Number(first) - Number(second) || byCodePoint(a, b);
  if (first || second) return first ? -1 : 1;
  return byCodePoint(a, b);
};
const indent = (text, spaces) => text.replace(/\n/g, `\n${' '.repeat(spaces)}`);

/**
 * `text` as runs of one kind each, `[kind, text]`, which spell the text again: keywords, strings
 * (a template string, `${}` parts included, is one run), comments, and the rest as `text`. The
 * scanner alone, with no parse, so the showcase colors code with the theme's tokens and needs no
 * highlighter.
 */
export function highlight(text) {
  const scanner = ts.createScanner(
    ts.ScriptTarget.Latest,
    false,
    ts.LanguageVariant.Standard,
    text,
  );
  const tokens = [];
  /** Open braces of each `${` being scanned; a `}` at zero closes it and the string goes on. */
  const templates = [];
  for (let at = 0, token = scanner.scan(); token !== ts.SyntaxKind.EndOfFileToken;) {
    let kind = templates.length ? 'string' : null;
    if (token === ts.SyntaxKind.TemplateHead) {
      templates.push(0);
      kind = 'string';
    } else if (token === ts.SyntaxKind.OpenBraceToken && templates.length) {
      templates[templates.length - 1]++;
    } else if (token === ts.SyntaxKind.CloseBraceToken && templates.length) {
      if (templates.at(-1)) templates[templates.length - 1]--;
      else if (scanner.reScanTemplateToken(false) === ts.SyntaxKind.TemplateTail) templates.pop();
    }
    const end = scanner.getTokenEnd();
    tokens.push({ token, kind, from: at, to: end });
    at = end;
    token = scanner.scan();
  }

  // Each token's significant neighbors (not whitespace or a comment), for `kindOf`.
  const significant = tokens.map((_, i) => i).filter((i) => !ts.isTrivia(tokens[i].token));
  const neighbors = new Map(
    significant.map((i, k) => [
      i,
      [tokens[significant[k - 1]]?.token, tokens[significant[k + 1]]?.token],
    ]),
  );
  const runs = [];
  for (const [i, entry] of tokens.entries()) {
    const kind = entry.kind ?? kindOf(entry.token, neighbors.get(i));
    const piece = text.slice(entry.from, entry.to);
    if (runs.at(-1)?.[0] === kind) runs.at(-1)[1] += piece;
    else runs.push([kind, piece]);
  }
  return runs;
}

/**
 * A stylesheet as runs: its comments, and the rest as `text`. Not the TypeScript scanner's job:
 * a CSS property named like a keyword (`content`, `in`) would be colored as one.
 */
export function highlightCss(text) {
  const runs = [];
  text.split(/(\/\*[\s\S]*?\*\/)/).forEach((piece, i) => {
    if (piece) runs.push([i % 2 ? 'comment' : 'text', piece]);
  });
  return runs;
}

/** What color a token that is not inside a template string gets. */
function kindOf(token, [before, after] = []) {
  if (
    token === ts.SyntaxKind.SingleLineCommentTrivia ||
    token === ts.SyntaxKind.MultiLineCommentTrivia
  ) {
    return 'comment';
  }
  if (
    token === ts.SyntaxKind.StringLiteral ||
    token === ts.SyntaxKind.NoSubstitutionTemplateLiteral
  ) {
    return 'string';
  }
  if (token < ts.SyntaxKind.FirstKeyword || token > ts.SyntaxKind.LastKeyword) return 'text';
  // A word that is a keyword only in some places (`type`, `from`) is a name after a dot or before
  // a colon: `obj.type`, `{ type: 1 }`.
  if (token > ts.SyntaxKind.LastReservedWord) {
    if (
      before === ts.SyntaxKind.DotToken ||
      before === ts.SyntaxKind.QuestionDotToken ||
      after === ts.SyntaxKind.ColonToken
    ) {
      return 'text';
    }
  }
  return 'keyword';
}

/** A class name in words: `MessagingPipeline` is "Messaging pipeline", `ROIEditor` "ROI editor". */
function titleOf(className) {
  const words = className
    .replace(/([a-z\d])([A-Z])/g, '$1 $2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .split(' ');
  return words
    .map((word, i) => {
      if (/^[A-Z]{2,}$/.test(word)) return word;
      return i ? word.toLowerCase() : word[0].toUpperCase() + word.slice(1).toLowerCase();
    })
    .join(' ');
}

const isExported = (statement) =>
  ts.getModifiers(statement)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) ?? false;

const isComponentDecorator = (decorator) =>
  ts.isCallExpression(decorator.expression) &&
  decorator.expression.expression.getText() === 'Component';

/** The kit parts a file imports, as `<import path>#<name>`, in the order written. */
function showsOf(sourceFile) {
  const shown = new Set();
  for (const statement of sourceFile.statements) {
    if (!ts.isImportDeclaration(statement)) continue;
    const from = statement.moduleSpecifier.text;
    if (from !== '@sima/neat-ui' && !from.startsWith('@sima/neat-ui/')) continue;
    for (const element of statement.importClause?.namedBindings?.elements ?? []) {
      if (ts.isImportSpecifier(element))
        shown.add(`${from}#${(element.propertyName ?? element.name).text}`);
    }
  }
  return [...shown];
}

/**
 * Reads the showcase's examples: every `*.example.ts` directly in a folder of `EXAMPLES_DIR`, the
 * folder being the topic. Each is one standalone component. Its class doc is its caption, which the
 * page shows as prose and the snippet leaves out, and may end in the bare tags that say how the
 * page shows it (`EXAMPLE_OPTIONS`); its other source is the snippet, as the file has it, plus the
 * files of its topic folder that it imports (a data file, say) and the stylesheets it names
 * (`styleUrl`) as extras. So what the page renders and what it shows are one file. Returns the
 * topics, each with its examples in file-name order, and the problems (a caption missing, a bad
 * class, an import that is no file of the topic folder); an example that cannot be read is left
 * out. The showcase's `app.ts` is appended to the examples of its topic (`SHELL_EXTRA`).
 */
export function extractExamples(root, kit = extractKit(root)) {
  const base = join(root, EXAMPLES_DIR);
  const found = [];
  const topics = [];
  if (existsSync(base)) {
    const folders = readdirSync(base, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort(byCodePoint);
    for (const topic of folders) {
      const examples = readTopic({ root, topic, kit, found });
      if (examples.length) topics.push({ topic, examples });
    }
  }
  // The shell's source joins its topic's examples when the topic has some, and is nothing else.
  const shell = topics.find((entry) => entry.topic === SHELL_EXTRA.topic);
  if (shell) {
    const example = readShellExtra({ root, kit, found, taken: shell.examples });
    if (example) shell.examples.push(example);
  }
  // Two examples that both import a data file report its problems twice.
  const problems = formatProblems([...new Map(found.map((p) => [JSON.stringify(p), p])).values()]);
  return { topics, problems };
}

/**
 * The one exported component of an example file, or undefined with the problem reported: an
 * example is one component.
 */
function exportedComponent(sourceFile, report) {
  const exported = sourceFile.statements.filter((s) => ts.isClassDeclaration(s) && isExported(s));
  if (exported.length !== 1) {
    const message = `has ${exported.length ? 'more than one' : 'no'} exported class; an example is one component`;
    report(exported[1] ?? sourceFile.statements[0] ?? sourceFile, message);
    return undefined;
  }
  const [cls] = exported;
  if (!ts.getDecorators(cls)?.some(isComponentDecorator)) {
    report(cls, `${cls.name.text} is not a component`);
    return undefined;
  }
  return cls;
}

/**
 * How the docs show an example, each a bare tag in its class doc: `@unpadded`, its live area
 * without the inset (a drawing that fills its card), `@page`, a route of its own that the card
 * links to (an example that needs the whole page: its own toolbar, tabs, panel or shell), and
 * `@gallery`, the one example whose picture stands for its topic in the README's gallery
 * (`tools/readme-gallery.mjs`), and `@animated`, an example whose point is motion, which the
 * Markdown docs show as an animation beside its still picture (`tools/docs-capture.mjs`), and
 * `@unpictured`, an example the Markdown docs show without a picture (one whose point is what a
 * widget reports to the app, which a picture cannot show). Tags that take words: `@capture`
 * (`parseCapture`), `@animated`'s optional length and rate (`parseAnimated`), `@play`, a step of
 * the script the docs' pictures run (`parsePlay`), and `@hide`, the controls they hide.
 */
const EXAMPLE_OPTIONS = ['unpadded', 'page', 'gallery', 'animated', 'unpictured'];

/** What `@capture` may do before the example's picture is taken (`tools/docs-capture.mjs`). */
export const CAPTURE_ACTIONS = ['click', 'hover'];

/**
 * An example's `@capture` tag, `@capture click <selector>` or `@capture hover <selector>`, read
 * from its lines (the first is the tag's own, the rest run on to the next tag or the comment's
 * end): the action and its CSS selector, or the reason it cannot be read. The picture of an
 * example whose content opens in an overlay (a popover, a dialog, a toast) shows that content.
 */
export function parseCapture(lines) {
  const [first = '', ...rest] = lines;
  if (rest.some((line) => line.trim())) return 'has text after it; the tag is one line';
  const match = first.trim().match(/^(\S+)\s+(.+)$/);
  if (!match)
    return `needs an action and a selector: @capture ${CAPTURE_ACTIONS.join('|')} <selector>`;
  const [, action, target] = match;
  if (!CAPTURE_ACTIONS.includes(action)) {
    return `has the action ${action}; it is ${CAPTURE_ACTIONS.join(' or ')}`;
  }
  return { action, target: target.trim() };
}

/** What a step of `@play` does (`tools/docs-capture.mjs`): hover or click a target, or wait. */
export const PLAY_ACTIONS = ['hover', 'click', 'wait'];

/** The longest a step of `@play` may wait, and an animation's bounds, so a typo cannot stall. */
const PLAY_WAIT_MAX_MS = 10_000;
const ANIMATION_SECONDS = [1, 20];
const ANIMATION_FPS = [5, 30];

/**
 * A line of tag text, or the reason it is not one: a tag runs on to the next one, so text on a
 * second line would be read as part of the tag, not of the caption.
 */
function tagLine(lines) {
  const [first = '', ...rest] = lines;
  return rest.some((line) => line.trim()) ? null : first.trim();
}

/**
 * An example's `@play` tag, one step of the script the docs' pictures run before a still and
 * during an animation (`tools/docs-capture.mjs`): `@play hover <selector>` or `@play click
 * <selector>`, a target in the example, optionally `at <x>%,<y>%` of its box before the selector
 * (its middle by default), or `@play wait <ms>`. The step, or the reason it cannot be read.
 */
export function parsePlay(lines) {
  const line = tagLine(lines);
  if (line === null) return 'has text after it; a step is one line';
  const [action = '', ...words] = line.split(/\s+/);
  if (!PLAY_ACTIONS.includes(action)) {
    return `has the action ${action || 'nothing'}; it is ${PLAY_ACTIONS.join(', ')}`;
  }
  if (action === 'wait') {
    const ms = Number(words.join(' ').replace(/ms$/, ''));
    if (!Number.isInteger(ms) || ms <= 0 || ms > PLAY_WAIT_MAX_MS) {
      return `wait takes a number of ms up to ${PLAY_WAIT_MAX_MS}`;
    }
    return { action, ms };
  }
  const rest = words.join(' ');
  const at = rest.match(/^at\s+(\d+(?:\.\d+)?)%,(\d+(?:\.\d+)?)%\s+(.+)$/);
  if (at) {
    const [x, y] = [Number(at[1]), Number(at[2])];
    if (x > 100 || y > 100) return 'has a point outside its target; at takes 0% to 100%';
    return { action, at: { x, y }, target: at[3].trim() };
  }
  if (rest.startsWith('at ')) return 'has an at that is not <x>%,<y>%';
  if (!rest) return `needs a selector: @play ${action} [at <x>%,<y>%] <selector>`;
  return { action, target: rest };
}

/**
 * An example's `@animated` tag: bare for the capture's default length and rate, or with either or
 * both, `@animated 6s 20fps`. Its options (`seconds`, `fps`, each only when given), or the reason
 * it cannot be read.
 */
export function parseAnimated(lines) {
  const line = tagLine(lines);
  if (line === null) return 'has text after it; the tag is one line';
  const timing = {};
  for (const word of line.split(/\s+/).filter(Boolean)) {
    const seconds = word.match(/^(\d+(?:\.\d+)?)s$/);
    const fps = word.match(/^(\d+)fps$/);
    if (seconds && timing.seconds === undefined) timing.seconds = Number(seconds[1]);
    else if (fps && timing.fps === undefined) timing.fps = Number(fps[1]);
    else return `has ${word}; it takes a length (6s) and a rate (20fps), each once`;
  }
  const outside = (value, [min, max]) => value !== undefined && (value < min || value > max);
  if (outside(timing.seconds, ANIMATION_SECONDS)) {
    return `runs ${timing.seconds}s; an animation runs ${ANIMATION_SECONDS.join(' to ')}s`;
  }
  if (outside(timing.fps, ANIMATION_FPS)) {
    return `has ${timing.fps}fps; the rate is ${ANIMATION_FPS.join(' to ')}fps`;
  }
  return timing;
}

/**
 * An example's caption (its class doc, which is prose and nothing else but the tags of
 * `EXAMPLE_OPTIONS`, `@capture`, `@play` and `@hide`), those options, and the file's text less that doc, since the page shows the
 * caption above the example and the snippet is what is left. A caption names only what an app can
 * import: the kit's hidden names are a problem here as in the doc comments of parts (`isHidden`),
 * so prose moved onto a page cannot leak internals.
 */
function readCaption({ cls, sourceFile, kit, report }) {
  const className = cls.name.text;
  const { body, tags } = rawDoc(cls);
  const options = {};
  for (const tag of tags) {
    if (tag.name === 'capture') {
      const capture = parseCapture(tag.lines);
      if (typeof capture === 'string') report(cls, `${className}'s @capture ${capture}`);
      else options.capture = capture;
    } else if (tag.name === 'play') {
      const step = parsePlay(tag.lines);
      if (typeof step === 'string') report(cls, `${className}'s @play ${step}`);
      else (options.play ??= []).push(step);
    } else if (tag.name === 'hide') {
      const target = tagLine(tag.lines);
      if (!target) report(cls, `${className}'s @hide needs a selector, on one line`);
      else if (options.hide) report(cls, `${className} has a second @hide; join the selectors`);
      else options.hide = target;
    } else if (tag.name === 'animated') {
      const timing = parseAnimated(tag.lines);
      if (typeof timing === 'string') report(cls, `${className}'s @animated ${timing}`);
      else {
        options.animated = true;
        if (Object.keys(timing).length) options.animation = timing;
      }
    } else if (!EXAMPLE_OPTIONS.includes(tag.name)) {
      report(cls, `${className}'s doc has the tag @${tag.name}; an example's doc is its caption`);
    } else if (tag.lines.some((line) => line.trim())) {
      // A tag runs on to the next one, so prose after it would be lost from the caption.
      report(cls, `${className}'s @${tag.name} has text after it; the tag stands alone`);
    } else options[tag.name] = true;
  }
  const caption = blocksOf(body, kit.names.public);
  if (!caption.length) report(cls, `${className} has no caption: write its doc comment`);
  for (const { code, name } of kitMentions(caption, kit.names.declared)) {
    if (isHidden(name, kit.names)) report(cls, hiddenMention(`${className}'s caption`, code));
  }
  const comment = ts.getJSDocCommentsAndTags(cls).filter(ts.isJSDoc).at(-1);
  let text = sourceFile.text;
  if (comment) {
    const end = comment.end + (text[comment.end] === '\n' ? 1 : 0);
    text = text.slice(0, comment.getStart()) + text.slice(end);
  }
  return { caption, options, text };
}

/**
 * The shell's source as an example (`SHELL_EXTRA`): code only, with no component to render.
 * `taken` are the topic's own examples, whose ids it must not repeat.
 */
function readShellExtra({ root, kit, found, taken }) {
  const path = join(root, SHOWCASE_APP, SHELL_EXTRA.file);
  if (!existsSync(path)) {
    const file = posix(relative(root, path));
    const message = `is the ${SHELL_EXTRA.topic} topic's extra example and does not exist`;
    found.push({ file, line: 1, message });
    return undefined;
  }
  const sourceFile = ts.createSourceFile(
    path,
    readFileSync(path, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
  );
  const report = (node, message) => found.push(problemAt(root, node, message));
  const cls = exportedComponent(sourceFile, report);
  if (!cls) return undefined;
  // The id is the example's anchor and key, so the topic's own examples may not use it.
  const same = taken.find((example) => example.id === SHELL_EXTRA.id);
  if (same) {
    report(
      cls,
      `the id ${SHELL_EXTRA.id} is already an example of this topic (${same.files[0].name})`,
    );
    return undefined;
  }
  const { caption, text } = readCaption({ cls, sourceFile, kit, report });
  return {
    id: SHELL_EXTRA.id,
    title: SHELL_EXTRA.title,
    caption,
    shows: showsOf(sourceFile),
    files: [{ name: SHELL_EXTRA.file, code: highlight(text) }],
  };
}

/** The topic's examples; its problems go into `found`. */
function readTopic({ root, topic, kit, found }) {
  const dir = join(root, EXAMPLES_DIR, topic);
  const parse = (file) =>
    ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const report = (node, message) => found.push(problemAt(root, node, message));

  /** The topic-folder files `sourceFile` imports, transitively, appended to `files` once each. */
  const addImports = (sourceFile, files) => {
    for (const statement of sourceFile.statements) {
      const specifier =
        (ts.isImportDeclaration(statement) || ts.isExportDeclaration(statement)) &&
        statement.moduleSpecifier;
      if (!specifier || !specifier.text.startsWith('.')) continue;
      const wanted = resolve(dirname(sourceFile.fileName), specifier.text);
      const file = [`${wanted}.ts`, join(wanted, 'index.ts')].find((path) => existsSync(path));
      if (!file || relative(dir, file).startsWith('..')) {
        report(statement, `imports '${specifier.text}', which is no file of its topic folder`);
      } else if (file.endsWith('.example.ts')) {
        report(statement, `imports '${specifier.text}', which is another example`);
      } else if (!files.some((entry) => entry.path === file)) {
        const extra = parse(file);
        files.push({ path: file, name: posix(relative(dir, file)), text: extra.text });
        addImports(extra, files);
      }
    }
  };

  /**
   * The stylesheets the component names (`styleUrl`, `styleUrls`), appended once each: an example's
   * layout is part of what renders, so a copy without it would not look as shown.
   */
  const addStyles = (cls, files) => {
    const decorator = ts.getDecorators(cls).find(isComponentDecorator);
    const options = decorator.expression.arguments[0];
    const urls = [
      property(options, 'styleUrl'),
      ...(property(options, 'styleUrls')?.elements ?? []),
    ];
    for (const url of urls.filter(Boolean)) {
      const text = literal(url);
      const file =
        text === undefined ? undefined : resolve(dirname(cls.getSourceFile().fileName), text);
      if (!file || !existsSync(file) || relative(dir, file).startsWith('..')) {
        report(url, `names the stylesheet ${url.getText()}, which is no file of its topic folder`);
      } else if (!files.some((entry) => entry.path === file)) {
        files.push({
          path: file,
          name: posix(relative(dir, file)),
          text: readFileSync(file, 'utf8'),
        });
      }
    }
  };

  const examples = [];
  const ids = new Map();
  const classes = new Map();
  let gallery = null;
  const names = readdirSync(dir)
    .filter((name) => name.endsWith('.example.ts'))
    .sort(byExampleName);
  for (const name of names) {
    const path = join(dir, name);
    const sourceFile = parse(path);
    const cls = exportedComponent(sourceFile, report);
    if (!cls) continue;
    const className = cls.name.text;
    const id = name.replace(/\.example\.ts$/, '').replace(/^\d+-/, '');
    if (ids.has(id) || classes.has(className)) {
      const same = ids.has(id) ? ids.get(id) : classes.get(className);
      report(
        cls,
        ids.has(id)
          ? `the id ${id} is already an example of this topic (${same})`
          : `${className} is already an example of this topic (${same})`,
      );
      continue;
    }
    ids.set(id, name);
    classes.set(className, name);

    const { caption, options, text } = readCaption({ cls, sourceFile, kit, report });
    if (options.animated && options.capture) {
      // An animation shows the example as it runs; one that acts says how with @play.
      report(cls, `${className} is @animated and has @capture; an animation acts by @play`);
      delete options.animated;
      delete options.animation;
    }
    if (options.play && options.capture) {
      report(cls, `${className} has @play and @capture; @play's steps do what @capture does`);
      delete options.capture;
    }
    if (options.unpictured) {
      // An example with no picture has none to stand for its topic, animate or act on.
      for (const tag of ['gallery', 'animated', 'capture', 'play', 'hide']) {
        if (!options[tag]) continue;
        report(cls, `${className} is @unpictured and has @${tag}; it has no picture`);
        delete options[tag];
      }
      delete options.animation;
    }
    if (options.gallery && gallery) {
      report(cls, `${className} is @gallery, and so is ${gallery}; a topic has one`);
      delete options.gallery;
    } else if (options.gallery) gallery = name;
    const files = [{ path, name, text }];
    addImports(sourceFile, files);
    addStyles(cls, files);

    examples.push({
      id,
      title: titleOf(className),
      component: className,
      ...options,
      caption,
      shows: showsOf(sourceFile),
      files: files.map((file) => ({
        name: file.name,
        code: file.name.endsWith('.css') ? highlightCss(file.text) : highlight(file.text),
      })),
    });
  }
  return examples;
}

/** The examples of one topic as its generated module. */
function renderExamples(topic, examples) {
  // An example with no component (the shell's) is code only: nothing to import.
  const imports = examples
    .filter((example) => example.component)
    .map((example) => {
      const from = pathPosix.relative(
        EXAMPLES_OUTPUT_DIR,
        `${EXAMPLES_DIR}/${topic}/${example.files[0].name.replace(/\.ts$/, '')}`,
      );
      return `import { ${example.component} } from '${from}';`;
    });
  const literal = (example) => {
    const json = (value) => indent(JSON.stringify(value, null, 2), 4);
    const files = example.files.map((file) => {
      // One row per source line (a template string or block comment spans several), so a change
      // to an example reads in the module as the lines it changed.
      const rows = [];
      let row = [];
      for (const token of file.code) {
        row.push(token);
        if (token[1].includes('\n')) rows.push(row.splice(0));
      }
      if (row.length) rows.push(row);
      const code = rows
        .map((r) => `          ${r.map((token) => JSON.stringify(token)).join(',')}`)
        .join(',\n');
      return [
        '      {',
        `        "name": ${JSON.stringify(file.name)},`,
        `        "code": [${code ? `\n${code}\n        ` : ''}]`,
        '      }',
      ].join('\n');
    });
    return [
      '  {',
      `    "id": ${JSON.stringify(example.id)},`,
      `    "title": ${JSON.stringify(example.title)},`,
      ...(example.component ? [`    "component": ${example.component},`] : []),
      ...EXAMPLE_OPTIONS.filter((name) => example[name]).map((name) => `    "${name}": true,`),
      ...(example.capture ? [`    "capture": ${JSON.stringify(example.capture)},`] : []),
      ...(example.animation ? [`    "animation": ${JSON.stringify(example.animation)},`] : []),
      ...(example.play ? [`    "play": ${JSON.stringify(example.play)},`] : []),
      ...(example.hide ? [`    "hide": ${JSON.stringify(example.hide)},`] : []),
      `    "caption": ${json(example.caption)},`,
      `    "shows": ${json(example.shows)},`,
      `    "files": [\n${files.join(',\n')}\n    ]`,
      '  }',
    ].join('\n');
  };
  const body = examples.map(literal).join(',\n');
  return (
    `${HEADER}import type { DocsExample } from '../../model';\n${imports.join('\n')}\n\n` +
    `export const EXAMPLES: readonly DocsExample[] = [\n${body},\n];\n`
  );
}

// --- output, check and watch ---------------------------------------------------------------------

/** The public API of every entry point of the kit at `root`, and the problems with its docs. */
export function extractKit(root) {
  return new KitReader(root).read();
}

function render(entry) {
  const data = JSON.stringify(entry, null, 2);
  return `${HEADER}import type { DocsEntry } from '../../model';\n\nexport const API: DocsEntry = ${data};\n`;
}

/** The modules `docs:emit` writes, by path from the root, and the doc problems. */
export function generate(root) {
  const kit = extractKit(root);
  const files = new Map(
    kit.entries.map((entry) => [`${OUTPUT_DIR}/${entry.entry}.ts`, render(entry)]),
  );
  const { topics, problems } = extractExamples(root, kit);
  for (const { topic, examples } of topics) {
    files.set(`${EXAMPLES_OUTPUT_DIR}/${topic}.ts`, renderExamples(topic, examples));
  }
  return { files, problems: [...kit.problems, ...problems] };
}

/** The files now in the output folders, by path from the root. */
function present(root) {
  return [OUTPUT_DIR, EXAMPLES_OUTPUT_DIR].flatMap((folder) => {
    const dir = join(root, folder);
    return existsSync(dir) ? readdirSync(dir).map((name) => `${folder}/${name}`) : [];
  });
}

/** Writes what changed and removes what is no longer generated, so the folder is the output. */
export function writeDocs(root) {
  const { files, problems } = generate(root);
  const written = [];
  for (const [path, content] of files) {
    const file = join(root, path);
    // Unchanged files are left alone, so a watching dev server rebuilds only for a real change.
    if (existsSync(file) && readFileSync(file, 'utf8') === content) continue;
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    written.push(path);
  }
  const removed = present(root).filter((path) => !files.has(path));
  for (const path of removed) rmSync(join(root, path));
  // With no examples there is no folder for them, as on a checkout before the first one.
  const examplesDir = join(root, EXAMPLES_OUTPUT_DIR);
  if (existsSync(examplesDir) && !readdirSync(examplesDir).length)
    rmSync(examplesDir, { recursive: true });
  return { written, removed, problems };
}

/** What `--check` finds: modules that differ, are missing or are extra, and doc problems. */
export function checkDocs(root) {
  const { files, problems } = generate(root);
  const stale = [];
  for (const [path, content] of files) {
    const file = join(root, path);
    if (!existsSync(file)) stale.push(`${path} is missing`);
    else if (readFileSync(file, 'utf8') !== content) stale.push(`${path} differs`);
  }
  for (const path of present(root)) {
    if (!files.has(path)) stale.push(`${path} is not generated`);
  }
  return { stale: stale.sort(), problems };
}

/** `--check`'s findings as the lines it prints; none when all is well. */
export function checkReport({ stale, problems }) {
  const list = (items) => items.map((item) => `  - ${item}`);
  return [
    ...(stale.length
      ? ['The committed docs are stale; run `npm run docs:emit`:', ...list(stale)]
      : []),
    ...(problems.length ? ['Doc problems:', ...list(problems)] : []),
  ];
}

function emit(root) {
  const { written, removed, problems } = writeDocs(root);
  const changes = [...written.map((p) => `wrote ${p}`), ...removed.map((p) => `removed ${p}`)];
  console.log(changes.length ? changes.join('\n') : 'The generated docs are up to date');
  if (problems.length) console.warn(checkReport({ stale: [], problems }).join('\n'));
}

/** Whether a change to `file`, relative to the library folder, can alter the API: a source file. */
export const changesKit = (file) => file.endsWith('.ts') && !file.endsWith('.spec.ts');

/**
 * Whether a change to `file`, relative to the showcase's app folder, can alter an example's
 * snippet: a source file of the examples folder or a stylesheet there (`styleUrl` files are
 * snippet extras), or the shell's own source (`SHELL_EXTRA`). The generated modules, beside it in
 * docs/, must not set the watch off again.
 */
export const changesExamples = (file) =>
  file === SHELL_EXTRA.file ||
  (file.split(/[\\/]/)[0] === 'examples' && (changesKit(file) || file.endsWith('.css')));

/** Writes now and after every change to the kit's source or the examples, until stopped. */
function watchKit(root) {
  const run = () => {
    try {
      emit(root);
    } catch (error) {
      console.error(error);
    }
  };
  run();
  let timer;
  const watchFolder = (folder, relevant) => {
    watch(join(root, folder), { recursive: true }, (_event, file) => {
      // Specs are in no program the docs read; a kit's stylesheets and templates hold no API.
      if (!file || !relevant(file)) return;
      clearTimeout(timer);
      timer = setTimeout(run, 100); // an editor's save is often several events
    });
  };
  watchFolder(LIBRARY, changesKit);
  // The app folder, not the examples folder: that one may not exist yet.
  watchFolder(SHOWCASE_APP, changesExamples);
  console.log(`Watching ${LIBRARY} and ${EXAMPLES_DIR} for changes (Ctrl+C stops).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  if (args.includes('--check')) {
    const report = checkReport(checkDocs(ROOT));
    if (report.length) {
      console.error(report.join('\n'));
      process.exit(1);
    }
    console.log(
      'The committed docs match the kit and the examples, and every public part has its docs.',
    );
  } else if (args.includes('--watch')) {
    watchKit(ROOT);
  } else {
    emit(ROOT);
  }
}
