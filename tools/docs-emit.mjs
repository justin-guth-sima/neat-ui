/** Reads one kit: the public API of each entry point, and the problems with its docs. */
class KitReader {
  constructor(root) {
    this.root = root;
    this.library = join(root, LIBRARY);
    this.entries = entryNames(root);
    this.program = createProgram(root);
    this.checker = this.program.getTypeChecker();
    this.problems = [];
    /** Kit identifiers the docs name, judged once every public member's name is known. */
    this.mentions = [];
  }

  read() {
    const exports = this.entries.map((entry) => {
      const packages = this.packageReexports(entry);
      const wholesale = new Set(packages.flatMap(({ symbols }) => symbols));
      const symbols = this.exportsOf(entry).filter((symbol) => !wholesale.has(symbol));
      return { entry, symbols, packages };
    });
    this.publicNames = new Set(exports.flatMap(({ symbols }) => symbols.map((s) => s.name)));
    this.kitNames = this.declaredNames();

    const entries = [];
    const reexports = [];
    for (const { entry, symbols, packages } of exports) {
      // The statement's doc is read now, once every public name is known to refer to.
      const parts = packages.map(({ name, statement }) => {
        const doc = this.doc(statement, name);
        if (!doc.blocks.length)
          this.problem(statement, `export * from '${name}' has no doc comment`);
        return {
          name,
          kind: 'reexport',
          package: true,
          import: importPath(entry),
          ...this.docFields(doc),
          source: posix(relative(this.root, this.entryFile(entry))),
        };
      });
      for (const symbol of symbols) {
        const target =
          symbol.flags & ts.SymbolFlags.Alias ? this.checker.getAliasedSymbol(symbol) : symbol;
        const declaration = target.declarations?.[0];
        const owner = declaration && this.owningEntry(declaration.getSourceFile().fileName);
        const specifier = symbol.declarations?.find(ts.isExportSpecifier);
        if (!owner) {
          this.problem(
            specifier ?? this.program.getSourceFile(this.entryFile(entry)),
            `${symbol.name} is declared outside the kit; export only the kit's own parts`,
          );
        } else if (owner !== entry) {
          const comment = specifier ? lineCommentAbove(specifier.parent.parent) : [];
          const note = blocksOf(comment, this.publicNames);
          parts.push({ name: symbol.name, kind: 'reexport', from: importPath(owner), note });
          reexports.push({ owner, name: symbol.name, import: importPath(entry), note });
        } else {
          parts.push(this.part(target, symbol.name));
        }
      }
      entries.push({ entry, import: importPath(entry), parts });
    }

    for (const { owner, name, import: from, note } of reexports) {
      const part = entries.find((e) => e.entry === owner).parts.find((p) => p.name === name);
      if (!part) {
        throw new Error(`${name} is re-exported from ${from} but not exported by its owner`);
      }
      (part.alsoExportedFrom ??= []).push({ import: from, note });
    }
    for (const entry of entries) entry.parts.sort(byName);

    // A name that is also a public part's member (a note's `along`) is that member.
    const members = new Set(memberNames(entries.flatMap((entry) => entry.parts)));
    const names = { declared: this.kitNames, public: this.publicNames, members };
    for (const { node, owner, code, name } of this.mentions) {
      if (isHidden(name, names)) this.problem(node, hiddenMention(owner, code));
    }
    return { entries, names, problems: this.problemList() };
  }

  entryFile(entry) {
    return entry === 'primary'
      ? join(this.library, 'src/public-api.ts')
      : join(this.library, entry, 'src/public-api.ts');
  }

  /**
   * The `export * from 'package'` statements of an entry whose package lies outside the kit: each
   * is one part named after the package, with the statement's doc, and its names are no parts of
   * their own (a package such as `lucide` exports thousands, and the docs cannot judge them).
   */
  packageReexports(entry) {
    const file = this.program.getSourceFile(this.entryFile(entry));
    const found = [];
    for (const statement of file.statements) {
      if (!ts.isExportDeclaration(statement) || statement.exportClause) continue;
      if (!statement.moduleSpecifier) continue;
      const module = this.checker.getSymbolAtLocation(statement.moduleSpecifier);
      const owner = module?.declarations?.[0]?.getSourceFile().fileName;
      if (!owner || this.isKitFile(owner)) continue;
      const name = statement.moduleSpecifier.text;
      found.push({ name, statement, symbols: this.checker.getExportsOfModule(module) });
    }
    return found;
  }

  /** The entry's exports, without `ɵ` names: the kit's shared internals, not for apps. */
  exportsOf(entry) {
    const file = this.program.getSourceFile(this.entryFile(entry));
    if (!file) throw new Error(`${this.entryFile(entry)} is not in the library's tsconfig`);
    return this.checker
      .getExportsOfModule(this.checker.getSymbolAtLocation(file))
      .filter((symbol) => !symbol.name.startsWith('ɵ'));
  }

  /** Every top-level name the kit's own source declares, public or not. */
  declaredNames() {
    const names = new Set();
    for (const file of this.program.getSourceFiles()) {
      if (file.isDeclarationFile || !this.isKitFile(file.fileName)) continue;
      for (const statement of file.statements) {
        if (ts.isVariableStatement(statement)) {
          for (const d of statement.declarationList.declarations) names.add(d.name.getText());
        } else if (statement.name && ts.isIdentifier(statement.name)) {
          names.add(statement.name.text);
        }
      }
    }
    return names;
  }

  isKitFile(fileName) {
    return !relative(this.library, fileName).startsWith('..');
  }

  /** The entry whose folder holds a file: `src/` is the primary, `<name>/src/` a secondary. */
  owningEntry(fileName) {
    const [first, second] = relative(this.library, fileName).split(sep);
    if (first === 'src') return 'primary';
    if (second === 'src' && this.entries.includes(first)) return first;
    return null;
  }

  problem(node, message) {
    this.problems.push(problemAt(this.root, node, message));
  }

  problemList() {
    return formatProblems(this.problems);
  }

  typeText(type) {
    return this.checker.typeToString(type, undefined, TYPE_TEXT);
  }

  /** A signal's type arguments (`InputSignalWithTransform<T, W>` gives T and W). */
  typeArguments(type) {
    if (type.flags & ts.TypeFlags.Object && type.objectFlags & ts.ObjectFlags.Reference) {
      // An interface's reference may carry its `this` type last; only the declared ones count.
      const declared = type.target.typeParameters?.length ?? 0;
      return this.checker.getTypeArguments(type).slice(0, declared);
    }
    return type.aliasTypeArguments ?? [];
  }

  /** Whether an identifier names Angular's own export, not a local helper of the same name. */
  isAngular(identifier) {
    let symbol = this.checker.getSymbolAtLocation(identifier);
    if (symbol && symbol.flags & ts.SymbolFlags.Alias) {
      symbol = this.checker.getAliasedSymbol(symbol);
    }
    const file = symbol?.declarations?.[0]?.getSourceFile().fileName ?? '';
    return /[/\\]@angular[/\\]core[/\\]/.test(file);
  }

  /** A doc as blocks, with its tags; problems in its text are reported against `owner`. */
  doc(node, owner) {
    const { body, tags } = rawDoc(node);
    const result = { blocks: this.blocks(body, node, owner), tags };
    const deprecated = tags.find((tag) => tag.name === 'deprecated');
    if (deprecated) result.deprecated = this.blocks(deprecated.lines, node, owner);
    for (const tag of tags.filter((t) => !TAGS.has(t.name))) {
      this.problem(node, `${owner} has the unknown tag @${tag.name}; its text would be lost`);
    }
    return result;
  }

  /** Doc text as blocks; what it names of the kit's own identifiers is kept to be judged. */
  blocks(lines, node, owner) {
    const blocks = blocksOf(lines, this.publicNames);
    for (const { code, name } of kitMentions(blocks, this.kitNames)) {
      this.mentions.push({ node, owner, code, name });
    }
    return blocks;
  }

  /** The doc fields of a part or member: `doc`, and `deprecated` when it is. */
  docFields(doc) {
    return { doc: doc.blocks, ...(doc.deprecated && { deprecated: doc.deprecated }) };
  }

  /** A part's doc, which every public part must have. */
  partDoc(node, name) {
    const doc = this.doc(node, name);
    if (!doc.blocks.length) this.problem(node, `${name} has no doc comment`);
    return doc;
  }

  part(symbol, name) {
    const declarations = symbol.declarations ?? [];
    const declaration = declarations[0];
    const source = posix(relative(this.root, declaration.getSourceFile().fileName));
    if (ts.isClassDeclaration(declaration)) return { ...this.classPart(declaration, name), source };

    if (ts.isFunctionDeclaration(declaration)) {
      const overloads = declarations.filter(ts.isFunctionDeclaration);
      const doc = this.partDoc(this.documented(overloads), name);
      const signature = this.signature(overloads, name);
      return { name, kind: 'function', signature, ...this.docFields(doc), source };
    }
    if (ts.isVariableDeclaration(declaration)) {
      const doc = this.partDoc(declaration, name);
      const init = declaration.initializer;
      if (init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init))) {
        const signature = this.signature([init], name);
        return { name, kind: 'function', signature, ...this.docFields(doc), source };
      }
      const type = declaration.type
        ? oneLine(declaration.type.getText())
        : this.typeText(this.checker.getTypeAtLocation(declaration.name));
      return { name, kind: 'const', type, ...this.docFields(doc), source };
    }
    if (ts.isTypeAliasDeclaration(declaration)) {
      const doc = this.partDoc(declaration, name);
      return {
        name,
        kind: 'type',
        ...this.typeParameters(declaration),
        definition: declaration.type.getText(),
        ...this.docFields(doc),
        source,
      };
    }
    if (ts.isInterfaceDeclaration(declaration)) {
      const doc = this.partDoc(declaration, name);
      const members = declaration.members.filter(ts.isPropertySignature).map((m) => ({
        name: m.name.getText(),
        type: m.type ? oneLine(m.type.getText()) : this.typeText(this.checker.getTypeAtLocation(m)),
        ...(m.questionToken && { optional: true }),
        ...this.docFields(this.doc(m, `${name}.${m.name.getText()}`)),
      }));
      const methods = this.methods(declaration.members.filter(ts.isMethodSignature), name);
      return {
        name,
        kind: 'interface',
        ...this.typeParameters(declaration),
        ...this.heritage(declaration),
        members,
        ...(methods.length && { methods }),
        ...this.docFields(doc),
        source,
      };
    }
    throw new Error(`${source}: ${name} is a ${ts.SyntaxKind[declaration.kind]}, not documented`);
  }

  typeParameters(node) {
    return node.typeParameters
      ? { typeParameters: node.typeParameters.map((t) => oneLine(t.getText())) }
      : {};
  }

  /** What a class or interface extends, as written: its members are documented there. */
  heritage(node) {
    const clause = node.heritageClauses?.find((h) => h.token === ts.SyntaxKind.ExtendsKeyword);
    return clause ? { extends: clause.types.map((t) => oneLine(t.getText())) } : {};
  }

  /** The first of several declarations (overloads) that has a doc comment, else the first. */
  documented(declarations) {
    return declarations.find((d) => rawDoc(d).body.some((l) => l.trim())) ?? declarations[0];
  }

  /** As written, one line per overload; an overloaded implementation's own is not public. */
  signature(declarations, name) {
    const shown = declarations.length > 1 ? declarations.filter((d) => !d.body) : declarations;
    return shown
      .map((d) => {
        const generics = d.typeParameters
          ? `<${d.typeParameters.map((t) => t.getText()).join(', ')}>`
          : '';
        const parameters = d.parameters.map((p) => p.getText()).join(', ');
        const returns = d.type
          ? d.type.getText()
          : this.typeText(this.checker.getSignatureFromDeclaration(d).getReturnType());
        return oneLine(`${name}${generics}(${parameters}): ${returns}`);
      })
      .join('\n');
  }

  /** Methods grouped by name (overloads together), in source order. */
  methods(declarations, owner) {
    const names = [...new Set(declarations.map((d) => d.name.getText()))];
    return names.map((name) => {
      const overloads = declarations.filter((d) => d.name.getText() === name);
      const doc = this.doc(this.documented(overloads), `${owner}.${name}`);
      return { name, signature: this.signature(overloads, name), ...this.docFields(doc) };
    });
  }

  angularDecorator(cls) {
    for (const decorator of ts.getDecorators(cls) ?? []) {
      const call = decorator.expression;
      if (!ts.isCallExpression(call) || !ts.isIdentifier(call.expression)) continue;
      if (!this.isAngular(call.expression)) continue;
      return { name: call.expression.text, meta: call.arguments[0] };
    }
    return null;
  }

  /** Whether a directive injects its own `TemplateRef`, which makes it a `*` directive. */
  injectsTemplateRef(cls) {
    const visit = (node) => {
      if (
        ts.isCallExpression(node) &&
        ts.isIdentifier(node.expression) &&
        node.expression.text === 'inject' &&
        this.isAngular(node.expression)
      ) {
        const [token] = node.arguments;
        if (token && ts.isIdentifier(token) && token.text === 'TemplateRef') return true;
      }
      return ts.forEachChild(node, visit) ?? false;
    };
    return visit(cls);
  }

  classKind(cls, decorator, selector) {
    if (decorator?.name === 'Component') return 'component';
    if (decorator?.name === 'Injectable') return 'service';
    if (decorator?.name !== 'Directive') return 'class';
    if (selector?.startsWith('ng-template[')) return 'template';
    return this.injectsTemplateRef(cls) ? 'structural' : 'directive';
  }

  classPart(cls, name) {
    const doc = this.partDoc(cls, name);
    const decorator = this.angularDecorator(cls);
    const selector = literal(property(decorator?.meta, 'selector'));
    const exportAs = literal(property(decorator?.meta, 'exportAs'));
    const kind = this.classKind(cls, decorator, selector);
    const hidden = ts.ModifierFlags.Private | ts.ModifierFlags.Protected | ts.ModifierFlags.Static;
    const isInternal = (member) => rawDoc(member).tags.some((tag) => tag.name === 'internal');

    const own = { input: [], model: [], output: [] };
    const properties = [];
    const methods = [];
    for (const member of cls.members) {
      if (ts.getCombinedModifierFlags(member) & hidden || isInternal(member)) continue;
      if (!member.name || ts.isPrivateIdentifier(member.name)) continue;
      const memberName = member.name.getText();
      if (ts.isMethodDeclaration(member)) {
        if (!HOOKS.has(memberName)) methods.push(member);
        continue;
      }
      if (!ts.isPropertyDeclaration(member) && !ts.isGetAccessorDeclaration(member)) continue;
      const signal = ts.isPropertyDeclaration(member) && this.signalCall(member.initializer);
      if (signal) {
        own[signal.fn].push(this.signalMember(member, signal, name));
      } else {
        const type = member.type
          ? oneLine(member.type.getText())
          : this.typeText(this.checker.getTypeAtLocation(member));
        const memberDoc = this.doc(member, `${name}.${memberName}`);
        properties.push({ name: memberName, type, ...this.docFields(memberDoc) });
      }
    }
    const forwarded = this.forwarded(cls, decorator?.meta, own, doc, name);
    const groups = {
      inputs: [...own.input, ...forwarded.input],
      models: [...own.model, ...forwarded.model],
      outputs: [...own.output, ...forwarded.output],
      context: kind === 'template' ? this.context(cls, name) : [],
      properties,
      methods: this.methods(methods, name),
    };
    return {
      name,
      kind,
      ...this.typeParameters(cls),
      ...this.heritage(cls),
      ...(selector && { selector }),
      ...(exportAs && { exportAs }),
      ...this.docFields(doc),
      ...Object.fromEntries(Object.entries(groups).filter(([, list]) => list.length)),
    };
  }

  /** `input(…)`, `input.required(…)`, `model(…)`, `model.required(…)`, `output(…)`, Angular's. */
  signalCall(init) {
    if (!init || !ts.isCallExpression(init)) return null;
    const callee = init.expression;
    let identifier = callee;
    let required = false;
    if (ts.isPropertyAccessExpression(callee) && callee.name.text === 'required') {
      identifier = callee.expression;
      required = true;
    }
    if (!ts.isIdentifier(identifier)) return null;
    const fn = identifier.text;
    if (!['input', 'model', 'output'].includes(fn) || !this.isAngular(identifier)) return null;
    return { fn, required, call: init };
  }

  signalMember(member, { fn, required, call }, owner) {
    // The options are the only argument of `output()` and of the required forms, else the second.
    const options = call.arguments[fn === 'output' || required ? 0 : 1];
    const alias = literal(property(options, 'alias'));
    const transform = property(options, 'transform')?.getText();
    const propertyName = member.name.getText();
    const [read, write] = this.typeArguments(this.checker.getTypeAtLocation(member));
    const [explicit, explicitWrite] = call.typeArguments ?? [];
    const name = alias ?? propertyName;
    const initial = fn !== 'output' && !required ? call.arguments[0] : undefined;
    const doc = this.doc(member, `${owner}.${name}`);
    if (!doc.blocks.length) this.problem(member, `${owner}.${name} has no doc comment`);
    return {
      name,
      ...(alias && { property: propertyName }),
      type: explicit ? oneLine(explicit.getText()) : this.typeText(read),
      ...(required && { required: true }),
      ...(initial && { default: oneLine(initial.getText()) }),
      ...(transform && { transform: oneLine(transform) }),
      ...(transform &&
        !ATTRIBUTE_TRANSFORMS.has(transform) && {
          accepts: explicitWrite ? oneLine(explicitWrite.getText()) : this.typeText(write),
        }),
      ...this.docFields(doc),
    };
  }

  /**
   * The bindings a part forwards from the primitives it hosts (`hostDirectives` inputs and
   * outputs), each under its public name and in the kit's words: the primitive is never named,
   * and its documentation is not the kit's, so each takes its doc from the part's `@input` or
   * `@output` tag. An own input or model of the same public name is that binding, and wins. A
   * forwarded model whose change output is forwarded beside it is a two-way binding.
   */
  forwarded(cls, meta, own, classDoc, owner) {
    const found = { input: [], model: [], output: [] };
    const taken = new Set([...own.input, ...own.model].map((m) => m.name));
    const parse = (spec) => {
      const [inner, alias] = spec.split(':').map((s) => s.trim());
      return { inner, name: alias ?? inner };
    };
    const hosts = property(meta, 'hostDirectives');
    for (const host of hosts && ts.isArrayLiteralExpression(hosts) ? hosts.elements : []) {
      const directive = property(host, 'directive');
      if (!directive) continue;
      const constructors = this.checker.getTypeAtLocation(directive).getConstructSignatures();
      const instance = constructors[0]?.getReturnType();
      const outputs = stringList(property(host, 'outputs')).map(parse);
      for (const { inner, name } of stringList(property(host, 'inputs')).map(parse)) {
        if (taken.has(name)) continue;
        const type = this.memberType(instance, inner);
        const change = outputs.findIndex(
          (o) => o.inner === `${inner}Change` && o.name === `${name}Change`,
        );
        if (this.isModelSignal(type) && change >= 0) {
          outputs.splice(change, 1);
          found.model.push({ name, type: this.vocabulary(this.typeArguments(type)[0]) });
        } else {
          // What a template may bind: the transform's input type where there is one.
          const [read, write] = type ? this.typeArguments(type) : [];
          const bound = write ?? read ?? type;
          found.input.push({ name, type: bound ? this.vocabulary(bound) : 'unknown' });
        }
      }
      for (const { inner, name } of outputs) {
        const type = this.memberType(instance, inner);
        const model = inner.endsWith('Change') && this.memberType(instance, inner.slice(0, -6));
        const emitted = type
          ? this.typeArguments(type)[0]
          : this.isModelSignal(model) && this.typeArguments(model)[0];
        found.output.push({ name, type: emitted ? this.vocabulary(emitted) : 'unknown' });
      }
    }

    const tagged = { input: new Map(), output: new Map() };
    for (const tag of classDoc.tags.filter((t) => t.name in tagged)) {
      const [first, ...rest] = tag.lines;
      const [, binding, text] = first.match(/^(\S*)\s*(.*)$/);
      tagged[tag.name].set(binding, [text, ...rest]);
    }
    const result = {};
    for (const [group, tag] of [
      ['input', 'input'],
      ['model', 'input'],
      ['output', 'output'],
    ]) {
      result[group] = found[group].map((binding) => {
        const lines = tagged[tag].get(binding.name);
        tagged[tag].delete(binding.name);
        if (!lines) {
          this.problem(
            cls,
            `${owner}.${binding.name} is forwarded and has no \`@${tag} ${binding.name}\` tag`,
          );
        }
        const doc = lines ? this.blocks(lines, cls, `${owner}.${binding.name}`) : [];
        return { ...binding, forwarded: true, doc };
      });
    }
    for (const [tag, rest] of Object.entries(tagged)) {
      for (const binding of rest.keys()) {
        this.problem(cls, `${owner} has an \`@${tag} ${binding}\` tag but forwards no ${binding}`);
      }
    }
    return result;
  }

  memberType(instance, name) {
    const symbol = instance?.getProperty(name);
    return symbol && this.checker.getTypeOfSymbol(symbol);
  }

  isModelSignal(type) {
    return !!type && type.getSymbol()?.getName() === 'ModelSignal';
  }

  /**
   * A forwarded binding's type in the kit's words: an alias declared outside the kit (brain's
   * `BrnTooltipPosition`, the CDK's `BooleanInput`) is spelled out, since apps see neither.
   */
  vocabulary(type) {
    const declaration = type.aliasSymbol?.declarations?.[0];
    if (!declaration || this.isKitFile(declaration.getSourceFile().fileName)) {
      return this.typeText(type);
    }
    const plain = ts.isTypeAliasDeclaration(declaration) && plainTypeText(declaration.type);
    return (
      plain ||
      this.checker.typeToString(type, undefined, TYPE_TEXT | ts.TypeFormatFlags.InTypeAlias)
    );
  }

  /**
   * A template directive's `let-` variables, from `ngTemplateContextGuard(…): context is X`. The
   * context type is not exported, so the docs show its members, not its name.
   */
  context(cls, owner) {
    const guard = cls.members.find(
      (m) => ts.isMethodDeclaration(m) && m.name.getText() === 'ngTemplateContextGuard',
    );
    if (!guard?.type || !ts.isTypePredicateNode(guard.type) || !guard.type.type) return [];
    const contextType = this.checker.getTypeFromTypeNode(guard.type.type);
    return contextType.getProperties().map((symbol) => {
      const declaration = symbol.valueDeclaration ?? symbol.declarations[0];
      const type = declaration.type
        ? oneLine(declaration.type.getText())
        : this.typeText(this.checker.getTypeOfSymbol(symbol));
      const doc = this.doc(declaration, `${owner} context ${symbol.name}`);
      return { name: symbol.name, type, ...this.docFields(doc) };
    });
  }
}

