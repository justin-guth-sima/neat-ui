/** A path with `/` as its separator on every platform. */
const posix = (path) => path.split(sep).join('/');

/**
 * A problem at `node`: its file (relative to `root`, with `/`), its line and the message. The line
 * is that of the node's name where it has one, which is where an editor should land.
 */
function problemAt(root, node, message) {
  const file = node.getSourceFile();
  const at = (node.name ?? node).getStart();
  const line = file.getLineAndCharacterOfPosition(at).line + 1;
  return { file: posix(relative(root, file.fileName)), line, message };
}

/** Problems as `file:line: message`, sorted by file and line. */
const formatProblems = (problems) =>
  problems
    .toSorted((a, b) => byCodePoint(a.file, b.file) || a.line - b.line)
    .map(({ file, line, message }) => `${file}:${line}: ${message}`);

/** `primary`, then the secondary entries: the folders beside `src` with an ng-package.json. */
function entryNames(root) {
  const library = join(root, LIBRARY);
  const secondaries = readdirSync(library, { withFileTypes: true })
    .filter((dir) => dir.isDirectory() && existsSync(join(library, dir.name, 'ng-package.json')))
    .map((dir) => dir.name)
    .sort();
  return ['primary', ...secondaries];
}

/** One program over the library's tsconfig: the root tsconfig's paths make it the whole kit. */
function createProgram(root) {
  const configFile = join(root, LIBRARY, 'tsconfig.lib.json');
  const config = ts.getParsedCommandLineOfConfigFile(
    configFile,
    {},
    {
      ...ts.sys,
      onUnRecoverableConfigFileDiagnostic: (diagnostic) => {
        throw new Error(ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'));
      },
    },
  );
  return ts.createProgram({
    rootNames: config.fileNames,
    options: { ...config.options, noEmit: true },
  });
}

// --- doc comments --------------------------------------------------------------------------------

/**
 * The doc comment right above `node`, from its raw text: its body lines and its tags. Not from
 * TypeScript's JSDoc parse, which starts a tag at any line-leading `@` and so cuts a comment short
 * at an Angular `@if` or `@for` inside a fenced example. Here a tag starts only outside a fence.
 * A tag on the line of the opening slash-star-star (a one-line comment) starts that line once it
 * is trimmed; later lines keep their indent, so an indented `@` stays prose.
 */
function rawDoc(node) {
  const comment = ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc).at(-1);
  if (!comment) return { body: [], tags: [] };
  const text = comment.getSourceFile().text.slice(comment.getStart(), comment.end);
  const lines = text
    .replace(/^\/\*\*/, '')
    .replace(/\*\/$/, '')
    .split('\n')
    .map((line, i) => (i === 0 ? line.trim() : line.replace(/^\s*\* ?/, '')));
  const body = [];
  const tags = [];
  let fenced = false;
  for (const line of lines) {
    if (/^\s*```/.test(line)) fenced = !fenced;
    const tag = !fenced && line.match(/^@(\w+)\s*(.*)$/);
    if (tag) tags.push({ name: tag[1], lines: [tag[2]] });
    else if (tags.length) tags.at(-1).lines.push(line);
    else body.push(line);
  }
  return { body, tags };
}

/**
 * Running text as spans: code spans, and `**` strong text around either. A code span that is
 * exactly a public name, or `Name.member`, is a reference. Unbalanced `**` stays as written.
 */
function spansOf(text, publicNames) {
  const pieces = text.split(/(`[^`]+`)/);
  const marks =
    pieces
      .filter((_, i) => i % 2 === 0)
      .join('')
      .split('**').length - 1;
  const spans = [];
  let strong = false;
  const push = (span) => {
    if (strong) span.strong = true;
    const last = spans.at(-1);
    if (span.kind === 'text' && last?.kind === 'text' && !last.strong === !span.strong) {
      last.text += span.text;
    } else spans.push(span);
  };
  pieces.forEach((piece, i) => {
    if (i % 2) {
      const code = piece.slice(1, -1);
      const [, name, member] = code.match(/^([\w$ɵ]+)(?:\.([\w$]+))?$/) ?? [];
      if (name && publicNames.has(name)) {
        push({ kind: 'ref', text: code, name, ...(member && { member }) });
      } else push({ kind: 'code', text: code });
      return;
    }
    const runs = marks && marks % 2 === 0 ? piece.split('**') : [piece];
    runs.forEach((run, j) => {
      if (j) strong = !strong;
      if (run) push({ kind: 'text', text: run });
    });
  });
  return spans;
}

/**
 * The Markdown subset the kit's doc comments use, as blocks: paragraphs (blank-line separated,
 * lines joined), fenced code with its language, and one level of `-` lists whose items run on
 * over the lines below them.
 */
function blocksOf(lines, publicNames) {
  const blocks = [];
  let paragraph = null;
  let list = null;
  const close = () => {
    if (paragraph) {
      blocks.push({ kind: 'paragraph', spans: spansOf(paragraph.join(' '), publicNames) });
    }
    if (list) {
      const items = list.map((item) => spansOf(item.join(' '), publicNames));
      blocks.push({ kind: 'list', items });
    }
    paragraph = list = null;
  };
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const fence = line.match(/^(\s*)```(\w*)\s*$/);
    if (fence) {
      close();
      const indent = fence[1].length;
      const code = [];
      for (i++; i < lines.length && !/^\s*```\s*$/.test(lines[i]); i++) {
        const own = lines[i].length - lines[i].trimStart().length;
        code.push(lines[i].slice(Math.min(indent, own)));
      }
      blocks.push({ kind: 'code', ...(fence[2] && { language: fence[2] }), code: code.join('\n') });
      continue;
    }
    if (!line.trim()) {
      close();
      continue;
    }
    const item = line.match(/^\s{0,3}- (.*)$/);
    if (item) {
      if (paragraph) close();
      (list ??= []).push([item[1].trim()]);
    } else if (list) list.at(-1).push(line.trim());
    else (paragraph ??= []).push(line.trim());
  }
  close();
  return blocks;
}

/**
 * What `blocks` may name of the kit's code: every code span (references included), and every word
 * of running text shaped like an identifier (`TONE_CLASSES`, `packTiles`), which a plain word
 * (`along`) is not.
 */
function mentions(blocks) {
  const spans = blocks.flatMap((block) =>
    block.kind === 'paragraph' ? block.spans : block.kind === 'list' ? block.items.flat() : [],
  );
  return spans.flatMap((span) =>
    span.kind === 'text'
      ? span.text.split(/[^\w$ɵ]+/).filter((word) => /_|[a-z][A-Z]/.test(word))
      : [span.text],
  );
}

/**
 * The kit identifiers `blocks` names, as `{ code, name }`: the code as written (`Name.member`) and
 * the name in it, for those the kit declares anywhere (`declared`).
 */
function kitMentions(blocks, declared) {
  const found = [];
  for (const code of new Set(mentions(blocks))) {
    const name = code.match(/^([\w$ɵ]+)(?:\.[\w$]+)?$/)?.[1];
    if (name && declared.has(name)) found.push({ code, name });
  }
  return found;
}

/**
 * Whether a kit name the docs mention is one they must not: declared by the kit but exported by no
 * entry (a `ɵ` name is never exported), and no member of a public part either (a note's `along`).
 * One rule for the doc comments of parts and for the captions of examples.
 */
const isHidden = (name, { public: exported, members }) => !exported.has(name) && !members.has(name);

/** The problem text for a doc of `owner` that names `code`. */
const hiddenMention = (owner, code) => `${owner} mentions \`${code}\`, which is not public`;

/** The names the members of `parts` are bound or called by. */
function memberNames(parts) {
  const groups = ['inputs', 'models', 'outputs', 'context', 'properties', 'methods', 'members'];
  return parts.flatMap((part) =>
    groups.flatMap((group) => part[group] ?? []).flatMap((m) => [m.name, m.property ?? []]),
  );
}

/** The `//` comment lines right above `statement`: why a re-export is there. */
function lineCommentAbove(statement) {
  const text = statement.getSourceFile().text;
  const ranges = ts.getLeadingCommentRanges(text, statement.getFullStart()) ?? [];
  const run = [];
  for (const range of ranges) {
    if (range.kind === ts.SyntaxKind.SingleLineCommentTrivia) run.push(range);
    else run.length = 0;
  }
  return run.map((range) => text.slice(range.pos, range.end).replace(/^\/\/ ?/, ''));
}

// --- decorators and types ------------------------------------------------------------------------

const literal = (expression) =>
  expression && ts.isStringLiteralLike(expression) ? expression.text : undefined;

/** The initializer of `key` in an object literal, if it has one. */
function property(object, key) {
  if (!object || !ts.isObjectLiteralExpression(object)) return undefined;
  const found = object.properties.find(
    (p) => ts.isPropertyAssignment(p) && p.name.getText() === key,
  );
  return found?.initializer;
}

const stringList = (expression) =>
  expression && ts.isArrayLiteralExpression(expression)
    ? expression.elements.map(literal).filter((text) => text !== undefined)
    : [];

const KEYWORD_TYPES = new Set([
  ts.SyntaxKind.StringKeyword,
  ts.SyntaxKind.NumberKeyword,
  ts.SyntaxKind.BooleanKeyword,
  ts.SyntaxKind.UndefinedKeyword,
  ts.SyntaxKind.UnknownKeyword,
  ts.SyntaxKind.AnyKeyword,
]);

/**
 * A union of literals and keywords, written in the kit's quotes; null for anything else. Used for
 * a third-party alias, whose definition as written keeps its author's order, where the checker
 * orders a union by when it first met each member and so by unrelated code.
 */
function plainTypeText(node) {
  if (ts.isUnionTypeNode(node)) {
    const members = node.types.map(plainTypeText);
    return members.includes(null) ? null : members.join(' | ');
  }
  if (ts.isLiteralTypeNode(node)) {
    return ts.isStringLiteral(node.literal)
      ? `'${node.literal.text.replace(/'/g, "\\'")}'`
      : node.getText();
  }
  return KEYWORD_TYPES.has(node.kind) ? node.getText() : null;
}

